// GET /api/config/sections: which "Others" sections have live listings (PG, Co-Ride, Rentals). Empty
// sections are reported live:false so the app hides them; one listing brings the section back; a count
// that cannot be read (model not loaded) is null and live:true, so a section is never hidden by mistake.
const test = require('node:test');
const assert = require('node:assert');
const path = require('path');
const H = require('./helpers');

let base; let server;
test.before(async () => {
  await H.setup();
  const seq = H.ctx.sequelize;
  H.r('models/PGHostel').initPGHostelModel(seq);
  H.r('models/BikePool').initBikePoolModel(seq);
  await seq.models.PGHostel.sync();
  await seq.models.BikePool.sync();
  const db = require(path.join(H.B, 'config/db.js'));
  db.getSequelize = () => seq;
  const express = require(path.join(H.B, 'node_modules/express'));
  const app = express();
  app.use('/api/config', H.r('routes/appConfigRoutes'));
  server = await require('../listenFree').listenFree(app);
  base = `http://127.0.0.1:${server.address().port}`;
});
test.after(async () => {
  if (server) await new Promise((res) => server.close(() => res()));
  await H.teardown();
});

const get = async () => {
  await H.r('utils/responseCache').invalidate('sections');
  const res = await fetch(`${base}/api/config/sections`);
  return { status: res.status, body: await res.json() };
};

test('empty catalogue: Co-Ride hidden; PG always shown (owner, 2 Nov 2026); Rentals unknown (model not loaded) shown', async () => {
  const r = await get();
  assert.strictEqual(r.status, 200);
  assert.deepStrictEqual(r.body.sections.pg, { count: 0, live: true });
  assert.deepStrictEqual(r.body.sections.coride, { count: 0, live: false });
  assert.deepStrictEqual(r.body.sections.rentals, { count: null, live: true });
});

test('one active PG is counted / one upcoming ride brings Co-Ride back; past or cancelled rides do not', async () => {
  const M = H.ctx.sequelize.models;
  const attrs = (Model) => Object.keys(Model.rawAttributes);
  const pgRow = { name: 'Real PG', isActive: true };
  for (const [k, a] of Object.entries(M.PGHostel.rawAttributes)) {
    if (a.allowNull === false && pgRow[k] === undefined && a.defaultValue === undefined && !a.primaryKey && !a._autoGenerated) {
      pgRow[k] = String(a.type).startsWith('FLOAT') || String(a.type).startsWith('INTEGER') || String(a.type).startsWith('DECIMAL') ? 1 : 'x';
    }
  }
  await M.PGHostel.create(pgRow);
  const ride = (extra) => {
    const row = { status: 'Available', departureTime: new Date(Date.now() + 3600 * 1000), ...extra };
    for (const [k, a] of Object.entries(M.BikePool.rawAttributes)) {
      if (a.allowNull === false && row[k] === undefined && a.defaultValue === undefined && !a.primaryKey && !a._autoGenerated) {
        const t = String(a.type);
        row[k] = t.startsWith('UUID') ? '00000000-0000-4000-8000-000000000001' : t.startsWith('FLOAT') || t.startsWith('INTEGER') || t.startsWith('DECIMAL') ? 1 : 'x';
      }
    }
    return M.BikePool.create(row);
  };
  await ride({ departureTime: new Date(Date.now() - 3600 * 1000) });
  await ride({ status: 'Cancelled' });
  let r = await get();
  assert.deepStrictEqual(r.body.sections.pg, { count: 1, live: true });
  assert.deepStrictEqual(r.body.sections.coride, { count: 0, live: false });
  await ride({});
  r = await get();
  assert.deepStrictEqual(r.body.sections.coride, { count: 1, live: true });
  assert.ok(attrs(M.PGHostel).includes('isActive'));
});

test('campus: the admin Campus (Friends) master switch is reported, and flipping it shows at once', async () => {
  const flags = H.r('modules/friends/services/featureFlags');
  const on = await get();
  assert.deepStrictEqual(on.body.sections.campus, { live: true }, 'on by default');
  // The admin switch (Admin > Friends app > Switches > Campus), without the test helper's cache drop.
  const GlobalConfig = H.ctx.sequelize.models.GlobalConfig;
  if (GlobalConfig) {
    const saved = await flags.setConfig({ enabled: false });
    assert.ok(!saved.errors, JSON.stringify(saved.errors));
    const res = await fetch(`${base}/api/config/sections`);
    assert.deepStrictEqual((await res.json()).sections.campus, { live: false }, 'off right after the switch');
    await flags.setConfig({ enabled: true });
    assert.deepStrictEqual((await get()).body.sections.campus, { live: true });
  }
});
